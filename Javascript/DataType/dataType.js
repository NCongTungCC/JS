// Kiểu dữ liệu cơ bản
let numberExample = 42; // Number
let stringExample = "Hello, world!"; // String
let booleanExample = true; // Boolean
let nullExample = null; // null
let undefinedExample; // undefined
let bigIntExample = 1234567890123456789012345678901234567890n; // BigInt
let symbolExample = Symbol("unique"); // Symbol

// Kiểu dữ liệu tham chiếu
let objectExample = { name: "John", age: 30 }; // Object
let arrayExample = [1, 2, 3, 4, 5]; // Array
let functionExample = function () {
  console.log("This is a function");
}; // Function

// In ra console để kiểm tra
console.log("Number:", numberExample);
console.log("String:", stringExample);
console.log("Boolean:", booleanExample);
console.log("Null:", nullExample);
console.log("Undefined:", undefinedExample);
console.log("BigInt:", bigIntExample);
console.log("Symbol:", symbolExample);
console.log("Object:", objectExample);
console.log("Array:", arrayExample);
console.log("Function:", functionExample);